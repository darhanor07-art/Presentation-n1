#!/usr/bin/env python3
"""Step 3: bake src/art/rigdata.js = refined rig artifacts (assets/rig/<char>/*.json) + retargeted CMU mocap tracks.
Run after refine_rigs.py:  python3 build/rigs/bake_rigdata.py"""
import os, json, math
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
RIG = os.path.join(ROOT, 'assets', 'rig'); MOC = os.path.join(ROOT, 'assets', 'mocap')

def ang_down(dx, dy): return math.degrees(math.atan2(-dx, dy))      # canvas rotation of a limb hanging down; dx already mirrored
def ang_up(dx, dy): return math.degrees(math.atan2(dx, -dy))        # canvas rotation of a limb pointing up

def tracks(clip, mirror=True):
    H = clip['height']; g = clip['groundY']; sx = -1 if mirror else 1; F = clip['frames']
    def P(f, k): return (sx * f[k][0], f[k][1])
    rows = []
    for f in F:
        hips = P(f, 'hips'); ch = P(f, 'chest'); hd = P(f, 'head')
        spine = ang_up(ch[0] - hips[0], ch[1] - hips[1]); headA = ang_up(hd[0] - ch[0], hd[1] - ch[1]) - spine
        r = {'spine': spine, 'head': headA}
        # screen +x side = mocap R in the mirrored (back) view
        for side, (s, e, h, k, ft, hp) in {'P': ('shR', 'elR', 'haR', 'knR', 'ftR', 'hipR'), 'N': ('shL', 'elL', 'haL', 'knL', 'ftL', 'hipL')}.items():
            a = P(f, s); b = P(f, e); c = P(f, h)
            up = ang_down(b[0] - a[0], b[1] - a[1]); lo = ang_down(c[0] - b[0], c[1] - b[1]) - up
            r['up' + side] = up; r['lo' + side] = lo
            hk = P(f, hp); kn = P(f, k)
            r['leg' + side] = ang_down(kn[0] - hk[0], kn[1] - hk[1])
            r['lift' + side] = (g - f[ft][1]) / H
        r['sway'] = (ch[0] - hips[0]) / H; r['bob'] = f['rootY'] / H
        r['shift'] = (P(f, 'knR')[0] + P(f, 'knL')[0]) / 2 / H
        rows.append(r)
    return rows

def highpass(vals, w):
    n = len(vals); out = []
    for i in range(n):
        lo = max(0, i - w); hi = min(n, i + w + 1); out.append(vals[i] - sum(vals[lo:hi]) / (hi - lo))
    return out

def bake_walk():
    c = json.load(open(os.path.join(MOC, 'walk.json'))); rows = tracks(c)[1:]
    P = 33
    keys = ['spine', 'head', 'upP', 'loP', 'upN', 'loN', 'legP', 'legN', 'liftP', 'liftN', 'sway', 'bob', 'shift']
    data = {}
    for k in keys:
        v = [r[k] for r in rows]
        if k == 'bob': v = highpass(v, 17)
        # make loopable: remove linear drift across one stride, then average the stride observed in 2 consecutive strides
        a = v[:P]; b = v[P:2 * P]; seg = [(a[i] + b[i]) / 2 for i in range(P)]
        d = (seg[-1] - seg[0]); seg = [seg[i] - d * i / P for i in range(P)]
        m = sum(seg) / P; data[k] = [round(x - m, 4) for x in seg]
    return {'fps': 30, 'n': P, 'loop': 'cycle', 'source': 'CMU walk (OpenMontage ink-theater walk.json), 1 stride = 2 steps', 'data': data}

def bake_sit():
    c = json.load(open(os.path.join(MOC, 'sit.json'))); rows = tracks(c)[1:]
    seg = rows[10:100]; keys = ['spine', 'head', 'upP', 'loP', 'upN', 'loN', 'sway', 'bob']; data = {}
    for k in keys:
        v = [r[k] for r in seg]
        if k == 'bob': v = highpass(v, 20)
        m = sum(v) / len(v); data[k] = [round(x - m, 4) for x in v]
    return {'fps': 30, 'n': len(seg), 'loop': 'pingpong', 'source': 'CMU sit (OpenMontage ink-theater sit.json) frames 11..100, ping-pong', 'data': data}

def main():
    out = {'mocap': {'walk': bake_walk(), 'sit': bake_sit()}, 'chars': {}}
    for cid in sorted(os.listdir(RIG)):
        d = os.path.join(RIG, cid)
        if cid == 'generated' or not os.path.isdir(d): continue
        L = lambda n: json.load(open(os.path.join(d, n + '.json')))
        rp = [c for c in L('rig_plan')['characters'] if c['character_id'] == cid][0]
        pl = [c for c in L('pose_library')['characters'] if c['character_id'] == cid][0]
        tl = L('action_timeline')
        scenes = {}
        for sc in tl['scenes']:
            scenes[sc['scene_id']] = {'start': sc['start_seconds'], 'end': sc['end_seconds'], 'actions': [a for a in sc['actions'] if a['character_id'] == cid]}
        out['chars'][cid] = {'scale': tl['metadata'].get('design_scale', {}).get(cid, 1000), 'parts': rp['parts'], 'joints': rp['joints'], 'poses': pl['poses'],
                             'cycles': pl.get('action_cycles', {}), 'scenes': scenes}
    js = '/* GENERATED by build/rigs/bake_rigdata.py from assets/rig/*/ (OpenMontage character-animation artifacts, refined) + CMU mocap (assets/mocap). Do not edit. */\n' \
         '(function () { var MK = window.MK; MK.rig.load(' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + '); })();\n'
    open(os.path.join(ROOT, 'src', 'art', 'rigdata.js'), 'w', encoding='utf-8').write(js)
    print('rigdata.js %.1f KB' % (len(js) / 1024))
if __name__ == '__main__': main()
